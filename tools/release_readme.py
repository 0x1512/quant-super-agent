#!/usr/bin/env python3
"""Release the README storefront (5th correction, internal #2/#3/#7).

    python tools/release_readme.py 1.4.1

What a release does, in order:

1. refresh docs/STATUS.json (version, today's date, recount the suite)
2. render the STATUS CARD into README.md / README.zh-CN.md from it
   (the card is the storefront's ONLY numeric content)
3. generate docs/STATUS.md — the in-repo status page the README links
   (NOT a CDN live page; four-channel delivery rules intact)
4. snapshot README.md + STATUS.md + STATUS.json into
   docs/releases/vX.Y.Z/ — the freeze baseline check_readme enforces

Between releases, main's README must stay byte-identical to the latest
snapshot (docs(readme):/release:/ci: commits excepted).
"""
from __future__ import annotations

import datetime
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from render_readme import card_text, render  # noqa: E402
from write_badge import count_tests  # noqa: E402

STATUS = ROOT / "docs" / "STATUS.json"


def main() -> int:
    if len(sys.argv) != 2 or not sys.argv[1][0].isdigit():
        print("usage: python tools/release_readme.py X.Y.Z")
        return 2
    version = "v" + sys.argv[1]
    status = json.loads(STATUS.read_text("utf-8"))
    status["version"] = sys.argv[1]
    status["date"] = datetime.date.today().isoformat()
    status["tests"] = count_tests()
    STATUS.write_text(json.dumps(status, ensure_ascii=False, indent=1)
                      + "\n", encoding="utf-8")

    # keep the badge endpoint in lockstep with the card's test count
    import sys as _sys
    import write_badge  # noqa: E402
    _argv = _sys.argv
    _sys.argv = [_argv[0]]          # our "X.Y.Z" arg is NOT badge output
    try:
        write_badge.main()
    finally:
        _sys.argv = _argv

    for path, lang in [(ROOT / "README.md", "en"),
                       (ROOT / "README.zh-CN.md", "zh")]:
        if path.exists():
            render(path, lang)
            print(f"[release] card rendered into {path.name}")

    # status page (in-repo, generated — never a CDN live page)
    s = status
    status_md = "\n".join([
        "# Project status",
        "",
        f"Machine-generated by `make release-readme` at **{version} "
        f"({s['date']})**. This page is the live-ish companion to the",
        "frozen README storefront; numbers here change only at release.",
        "",
        card_text("en"),
        "",
        "## Where the fresher numbers live",
        "",
        "- Per-round run log: [NEWS.md](NEWS.md)",
        "- Case archive (dates / fingerprints / reproduce commands): "
        "[CASES.md](CASES.md)",
        "- Machine-regenerable tour baseline: [TOUR_NUMBERS.json]"
        "(TOUR_NUMBERS.json) — `make tour` re-derives and drift-alarms",
        "- Full evidence inventory: [EVIDENCE.md](EVIDENCE.md)",
        "- Dev-facing status (may churn freely): [../README.dev.md]"
        "(../README.dev.md)",
        "",
        "## Reproduce the reference numbers yourself",
        "",
        "```",
        "make verify        # the suite behind the tests badge",
        "make offense-full  # the reference full run behind the card",
        "make tour          # regenerate + drift-check the tour numbers",
        "```",
        "",
    ]) + "\n"
    (ROOT / "docs" / "STATUS.md").write_text(status_md, encoding="utf-8")
    print("[release] docs/STATUS.md written")

    snap_dir = ROOT / "docs" / "releases" / version
    snap_dir.mkdir(parents=True, exist_ok=True)
    for src, name in [(ROOT / "README.md", "README.md"),
                      (ROOT / "docs" / "STATUS.md", "STATUS.md"),
                      (STATUS, "STATUS.json")]:
        shutil.copyfile(src, snap_dir / name)
    print(f"[release] snapshot -> {snap_dir.relative_to(ROOT)}/")
    print("[release] storefront frozen until the next release")
    return 0


if __name__ == "__main__":
    sys.exit(main())
